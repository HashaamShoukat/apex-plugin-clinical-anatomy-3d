-- Clinical Anatomy 3D: optional demonstration storage, separate from the shared catalog.
set define off
begin
    execute immediate 'create table ca3d_demo_records (
        id number generated by default on null as identity primary key,
        workspace_id number not null,
        application_id number not null,
        owner_user varchar2(255) not null,
        title varchar2(120) not null,
        specialty_code varchar2(30) default ''ALL'' not null,
        assessment_json clob not null check (assessment_json is json),
        created_at timestamp with time zone default systimestamp not null
    )';
exception when others then if sqlcode != -955 then raise; end if;
end;
/
create or replace view ca3d_demo_records_v as
select id, title, specialty_code, assessment_json, owner_user, created_at
  from ca3d_demo_records
 where workspace_id = apex_custom_auth.get_security_group_id
   and application_id = to_number(v('APP_ID'))
   and (owner_user = upper(v('APP_USER')) or owner_user = '#SAMPLE#');
/
create or replace package ca3d_demo_api as
    function save_record(p_title varchar2, p_specialty varchar2, p_json clob) return number;
end ca3d_demo_api;
/
create or replace package body ca3d_demo_api as
    function save_record(p_title varchar2, p_specialty varchar2, p_json clob) return number is
        l_id number;
        l_error varchar2(4000);
        l_json json_object_t;
        l_sites json_array_t;
    begin
        if v('APP_USER') is null or upper(v('APP_USER')) in ('NOBODY','APEX_PUBLIC_USER') then
            raise_application_error(-20001,'Sign in before saving a demonstration record.');
        end if;
        if trim(p_title) is null or length(p_title)>120 then
            raise_application_error(-20002,'Enter a title of up to 120 characters.');
        end if;
        if p_specialty is not null and p_specialty not in ('ALL','ENT','OPHTHALMOLOGY','CARDIOLOGY','UROLOGY','INTERNAL_MEDICINE','GASTROENTEROLOGY','NEUROLOGY','PULMONOLOGY','ORTHOPEDICS') then
            raise_application_error(-20005,'Choose a supported specialty.');
        end if;
        l_error := skeleton3d_pkg.validate_payload(p_json);
        if l_error is not null then raise_application_error(-20003,l_error); end if;
        l_error := ca3d_clinic_api.validate_value(p_json,'OPTIONAL');
        if l_error is not null then raise_application_error(-20003,l_error); end if;
        l_json := json_object_t.parse(p_json);
        l_sites := l_json.get_array('sites');
        if l_sites is null or l_sites.get_size=0 then
            raise_application_error(-20004,'Select at least one anatomical site before saving.');
        end if;
        insert into ca3d_demo_records(workspace_id,application_id,owner_user,title,specialty_code,assessment_json)
        values(apex_custom_auth.get_security_group_id,to_number(v('APP_ID')),upper(v('APP_USER')),trim(p_title),nvl(p_specialty,'ALL'),p_json)
        returning id into l_id;
        return l_id;
    end;
end ca3d_demo_api;
/
-- Idempotent fictional examples. These contain no patient identifiers.
declare
    l_count number;
    l_workspace number := coalesce(apex_custom_auth.get_security_group_id,apex_application_install.get_workspace_id);
    l_application number := coalesce(nullif(apex_application_install.get_application_id,0),to_number(v('APP_ID')),nullif(apex_application.g_flow_id,0));
    procedure seed(p_title varchar2,p_specialty varchar2,p_json clob) is
    begin
        select count(*) into l_count from ca3d_demo_records
         where workspace_id=l_workspace and application_id=l_application
           and owner_user='#SAMPLE#' and title=p_title;
        if l_count=0 then
            insert into ca3d_demo_records(workspace_id,application_id,owner_user,title,specialty_code,assessment_json)
            values(l_workspace,l_application,'#SAMPLE#',p_title,p_specialty,p_json);
        end if;
    end;
begin
    -- Seed only when called in the destination application's APEX context.
    if l_workspace is null or l_application is null then return; end if;
    seed('Sample: left kidney finding','UROLOGY',q'~{"v":2,"sex":"F","sites":[{"area":"KIDNEY","side":"L","note":"Fictional demonstration finding","assessment":"ABNORMAL","diagnoses":[],"markers":[{"id":"sample-renal","kind":"POINT","points":[[-0.07,1.04,-0.04]],"label":"Sample finding","diagnosis":null}]}]}~');
    seed('Sample: heart and lung review','CARDIOLOGY',q'~{"v":2,"sex":"M","sites":[{"area":"HEART","note":"Fictional demonstration review","assessment":"NORMAL","diagnoses":[]},{"area":"LUNG","side":"R","note":"Fictional demonstration finding","assessment":"ABNORMAL","diagnoses":[]}]}~');
end;
/
