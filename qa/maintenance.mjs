import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const url = pathToFileURL('demo/demo.html').href;
let count = 0;
const check = (name, value) => { assert.ok(value, name); count++; console.log('ok   ' + name); };
try {
    const page = await browser.newPage({ viewport: { width: 1500, height: 1100 } });
    const errors = []; page.on('pageerror', e => errors.push(String(e)));
    await page.goto(url + '?clinic=MIXED&exam=REQUIRED&tools=ALL');
    await page.waitForFunction(() => skeleton3d.get('P1_BODY').widget.clinic.loaded);
    check('doctor preview has no maintenance controls', await page.locator('[data-clinic="configure-exam"],[data-clinic="new-diagnosis"]').count() === 0);
    await page.goto(url + '?maintainer=1&tools=ALL&scope=MAINTENANCE' + Date.now());
    await page.waitForFunction(() => skeleton3d.get('P1_BODY').widget.clinic.loaded);
    check('maintenance toolbar appears with Standard mode and examination Off', await page.locator('.sk3-maintenance').isVisible());
    check('configuration is available before any site is selected', await page.locator('[data-clinic="configure-exam"]').isEnabled());
    check('creation prompts for anatomy before allowing a write', await page.locator('[data-clinic="new-diagnosis"]').isDisabled());
    await page.evaluate(() => skeleton3d.get('P1_BODY').setSpecialty('CARDIOLOGY'));
    await page.locator('[data-act="controls"]').click();
    await page.locator('[data-model-check="parts"]').check();
    await page.locator('[data-model="browser"]').click();
    await page.locator('[data-model-search]').fill('mitral');
    await page.locator('[data-model="structure"]').first().click();
    await page.locator('[data-model="record-structure"]').click();
    await page.locator('[data-model="close-browser"]').click();
    await page.locator('[data-clinic="new-diagnosis"]').click();
    await page.locator('[name="clinic-label"]').fill('Clinic mitral finding');
    await page.locator('[name="clinic-code"]').fill('CL-MV-001');
    await page.locator('[data-clinic="save-term"]').click();
    await page.locator('.sk3-dialog:not(.sk3-exam-dialog):not(.sk3-context-dialog)').waitFor({ state: 'detached' });
    check('creation retains selected structure, specialty and code', await page.evaluate(() => {
        const s = skeleton3d.get('P1_BODY').value().sites.find(s => s.part === 'MITRAL_VALVE');
        return s?.diagnoses.some(d => d.id > 0 && d.code === 'CL-MV-001' && d.specialty === 'CARDIOLOGY');
    }));
    check('part-specific terms do not leak into the whole organ', await page.evaluate(async () => (await skeleton3d.get('P1_BODY').widget.clinic.terms('DIAGNOSIS', ['HEART'])).length === 0));
    check('part-specific terms can be reused on the selected structure', await page.evaluate(async () => (await skeleton3d.get('P1_BODY').widget.clinic.terms('DIAGNOSIS', ['HEART'], '', 'MITRAL_VALVE')).length === 1));
    await page.locator('[data-act="controls"]').click();
    await page.locator('.sk3-view-controls').screenshot({ path: 'qa/out/clinic-controls-desktop.png' });
    await page.locator('[data-model="close-controls"]').click();
    await page.locator('[data-clinic="configure-exam"]').click();
    check('configuration includes a clinical starter and section selectors', await page.locator('[data-clinic="use-starter"]').isVisible() && await page.locator('[name="section"]').count() > 20);
    await page.locator('[data-clinic="close-dialog"]').click();
    await page.evaluate(()=>localStorage.removeItem('skeleton3d-clinic-demo'));
    await page.goto(url + '?exam=REQUIRED&tools=ALL&maintainer=1');
    await page.waitForFunction(() => skeleton3d.get('P1_BODY').widget.clinic.loaded);
    await page.locator('.sk3-topbar [data-clinic="show-exam"]').click();
    check('assessment is grouped into three sections', await page.locator('.sk3-exam-section').count() === 3);
    check('assessments are never prefilled as normal', await page.locator('[data-exam-value="general"]:checked').count() === 0);
    await page.locator('.sk3-exam-section').first().screenshot({ path: 'qa/out/clinic-history-desktop.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    check('workspace and form fit a phone', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.locator('.sk3-exam-section').first().screenshot({ path: 'qa/out/clinic-history-phone.png' });
    check('no browser exceptions', errors.length === 0);
    console.log(count + ' maintenance and form checks passed');
} finally { await browser.close(); }
